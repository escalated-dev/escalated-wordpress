// Generate .po files for each language
const languages = {
  es_ES: { name: 'Spanish', nplurals: 2, plural: '(n != 1)' },
  fr_FR: { name: 'French', nplurals: 2, plural: '(n > 1)' },
  de_DE: { name: 'German', nplurals: 2, plural: '(n != 1)' },
  ja: { name: 'Japanese', nplurals: 1, plural: '0' },
  pt_BR: { name: 'Portuguese (Brazil)', nplurals: 2, plural: '(n > 1)' },
};

for (const [locale, langInfo] of Object.entries(languages)) {
  const dict = translations[locale] || {};
  let po = `# ${langInfo.name} translation for Escalated
# Copyright (C) 2025 Escalated
# This file is distributed under the GPL-2.0-or-later.
msgid ""
msgstr ""
"Project-Id-Version: Escalated 1.0.0\\n"
"Report-Msgid-Bugs-To: https://github.com/escalated-dev/escalated-wordpress/issues\\n"
"Last-Translator: Escalated Team\\n"
"Language-Team: ${langInfo.name}\\n"
"Language: ${locale}\\n"
"MIME-Version: 1.0\\n"
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8bit\\n"
"POT-Creation-Date: 2026-04-05T00:00:00+00:00\\n"
"PO-Revision-Date: 2026-04-05T00:00:00+00:00\\n"
"X-Generator: Escalated\\n"
"X-Domain: escalated\\n"
"Plural-Forms: nplurals=${langInfo.nplurals}; plural=${langInfo.plural};\\n"

`;

  let translated = 0;
  let total = 0;

  for (const entry of entries) {
    total++;
    const msgid = entry.msgid;
    // Unescape for lookup
    const lookupKey = msgid.replace(/\\"/g, '"').replace(/\\\\/g, '\\');
    const translation = dict[lookupKey] || '';

    if (translation) translated++;

    for (const ref of entry.refs) {
      po += ref + '\n';
    }
    po += `msgid "${msgid}"\n`;
    // Escape the translation for .po format
    const escapedTranslation = translation.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
    po += `msgstr "${escapedTranslation}"\n`;
    po += '\n';
  }

  const filePath = path.join(rootDir, 'languages', `escalated-${locale}.po`);
  fs.writeFileSync(filePath, po);
  console.log(`${locale}: ${translated}/${total} strings translated -> ${filePath}`);
}

