const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const potContent = fs.readFileSync(path.join(rootDir, 'languages', 'escalated.pot'), 'utf8');

// Parse .pot file to get all msgids with their references
const entries = [];
const blocks = potContent.split('\n\n');
for (const block of blocks) {
  const lines = block.trim().split('\n');
  if (!lines.length) continue;

  const refs = [];
  let msgid = '';

  for (const line of lines) {
    if (line.startsWith('#: ')) refs.push(line);
    if (line.startsWith('msgid "')) {
      msgid = line.slice(7, -1); // remove msgid " and trailing "
    }
  }

  if (msgid && refs.length > 0) {
    entries.push({ refs, msgid });
  }
}

console.log(`Parsed ${entries.length} translatable entries`);

